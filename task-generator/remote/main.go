// Adapted from container-build-catalog/task-generator/remote at 85e9667.
// Preserve its source-Task -> generated-Task approach and controller contract.
// Unlike the Buildah generator, split local execution and trusted SSH into
// different steps, because the source Task's image is developer-controlled.
package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"

	"gopkg.in/yaml.v3"
)

// mount constructs a volume mount shared by generated trusted steps.
func mount(name, path string) map[string]any {
	return map[string]any{
		"name":      name,
		"mountPath": path,
	}
}

// when limits a generated execution step to the selected local or remote mode.
func when(mode string) []any {
	return []any{map[string]any{"input": "$(steps.select-platform.results.MODE)", "operator": "in", "values": []any{mode}}}
}

// items returns a YAML sequence, treating an absent optional field as empty.
func items(m map[string]any, key string) []any {
	result, _ := m[key].([]any)
	return result
}

// convert adds controller-selected local and remote execution to the source Task.
func convert(task map[string]any, stepName, taskName string) error {
	spec, ok := task["spec"].(map[string]any)
	if !ok {
		return fmt.Errorf("missing Task spec")
	}

	steps, err := taskSteps(spec)
	if err != nil {
		return err
	}

	builder, prepare := findBuildAndPrepare(steps, stepName)
	if builder == nil {
		return fmt.Errorf("missing build step %q", stepName)
	}

	if prepare == nil {
		return fmt.Errorf("missing trusted prepare step")
	}

	trustedImage := prepare["image"]
	builder["name"] = "build-local"
	builder["when"] = when("local")

	selectStep := selectPlatformStep(trustedImage)
	remoteStep := remoteBuildStep(trustedImage)
	recordStep := recordImageStep(trustedImage)
	spec["steps"] = routeSteps(steps, builder, selectStep, remoteStep, recordStep)
	addGeneratedTaskContracts(spec)

	metadata, ok := task["metadata"].(map[string]any)
	if !ok {
		return fmt.Errorf("missing Task metadata")
	}

	metadata["name"] = taskName
	spec["description"] = "Generated BYOB Task supporting controller-selected localhost execution " +
		"and rootless Podman on remote VMs."
	return nil
}

// taskSteps converts the source steps to maps and reports malformed step values.
func taskSteps(spec map[string]any) ([]map[string]any, error) {
	var steps []map[string]any
	for index, item := range items(spec, "steps") {
		step, ok := item.(map[string]any)
		if !ok || step == nil {
			return nil, fmt.Errorf("step %d must be a mapping", index)
		}

		steps = append(steps, step)
	}

	return steps, nil
}

// findBuildAndPrepare finds the developer step and the trusted CLI image source.
func findBuildAndPrepare(steps []map[string]any, stepName string) (map[string]any, map[string]any) {
	var builder, prepare map[string]any
	for _, step := range steps {
		if step["name"] == stepName {
			builder = step
		}

		if step["name"] == "prepare" {
			prepare = step
		}
	}

	return builder, prepare
}

// selectPlatformStep builds the trusted step that reads the controller's execution mode.
func selectPlatformStep(trustedImage any) map[string]any {
	sshMount := mount("ssh", "/ssh")
	sshMount["readOnly"] = true
	return map[string]any{
		"name":         "select-platform",
		"image":        trustedImage,
		"command":      []any{"/usr/local/bin/byob"},
		"args":         []any{"select-platform", "--ssh-dir=/ssh", "--result=$(step.results.MODE.path)"},
		"volumeMounts": []any{sshMount},
		"results":      []any{map[string]any{"name": "MODE", "type": "string"}},
	}
}

// remoteBuildStep builds the trusted VM step with separate credential and workdir mounts.
func remoteBuildStep(trustedImage any) map[string]any {
	sshMount := mount("ssh", "/ssh")
	sshMount["readOnly"] = true

	return map[string]any{
		"name":    "build-remote",
		"image":   trustedImage,
		"command": []any{"/usr/local/bin/byob"},
		"args": []any{
			"build-remote",
			"--ssh-dir=/ssh",
			"--source=/var/source",
			"--inputs=/var/workdir/inputs",
			"--control=/var/workdir/control",
			"--image=$(params.image)",
			"--",
			"$(params.build-cmd[*])",
			"$(params.build-args[*])",
		},
		"when": when("remote"),
		"volumeMounts": []any{
			sshMount,
			mount("source", "/var/source"),
			mount("workdir", "/var/workdir"),
		},
	}
}

// recordImageStep emits the trusted metadata result for the image used in the build.
func recordImageStep(trustedImage any) map[string]any {
	properties := imageArtifactProperties()
	return map[string]any{
		"name":    "record-image",
		"image":   trustedImage,
		"command": []any{"/usr/local/bin/byob"},
		"args": []any{
			"record-image",
			"--mode=$(steps.select-platform.results.MODE)",
			"--image=$(params.image)",
			"--control=/var/workdir/control",
			"--result=$(step.results.BUILD_IMAGE_ARTIFACT_INPUTS.path)",
		},
		"volumeMounts": []any{mount("workdir", "/var/workdir")},
		"results": []any{
			map[string]any{
				"name":       "BUILD_IMAGE_ARTIFACT_INPUTS",
				"type":       "object",
				"properties": properties,
			},
		},
	}
}

// routeSteps replaces the local build step with selection, local, remote, and metadata steps.
func routeSteps(steps []map[string]any, builder, selectStep, remoteStep, recordStep map[string]any) []any {
	routed := make([]any, 0, len(steps)+3)
	for _, step := range steps {
		if step["name"] == "build-local" {
			routed = append(routed, selectStep, builder, remoteStep, recordStep)
			continue
		}

		if step["name"] == "validate-output" {
			step["args"] = append(items(step, "args"), "--platform=$(params.PLATFORM)")
		}

		routed = append(routed, step)
	}

	return routed
}

// addGeneratedTaskContracts appends the controller parameter, Secret, and image result.
func addGeneratedTaskContracts(spec map[string]any) {
	spec["params"] = append(items(spec, "params"), map[string]any{
		"name":        "PLATFORM",
		"type":        "string",
		"description": "Controller platform; local-platforms may resolve this to localhost.",
	})
	spec["volumes"] = append(items(spec, "volumes"), map[string]any{
		"name":   "ssh",
		"secret": map[string]any{"secretName": "multi-platform-ssh-$(context.taskRun.name)"},
	})
	spec["results"] = append(items(spec, "results"), map[string]any{
		"name":       "BUILD_IMAGE_ARTIFACT_INPUTS",
		"type":       "object",
		"properties": imageArtifactProperties(),
		"value":      "$(steps.record-image.results.BUILD_IMAGE_ARTIFACT_INPUTS)",
	})
}

// imageArtifactProperties defines the URI and digest fields on image metadata results.
func imageArtifactProperties() map[string]any {
	return map[string]any{
		"uri":    map[string]any{"type": "string"},
		"digest": map[string]any{"type": "string"},
	}
}

// run reads the source Task and writes its generated remote variant.
func run() error {
	input := flag.String("task", "", "source Task YAML")
	output := flag.String("remote-task", "", "generated Task YAML")
	step := flag.String("step", "build", "developer step to wrap")
	name := flag.String("name", "run-build-remote", "generated Task name")
	flag.Parse()
	if *input == "" || *output == "" {
		return fmt.Errorf("--task and --remote-task are required")
	}

	return generate(*input, *output, *step, *name)
}

// generate reads the source Task, applies remote execution, and writes the generated YAML.
func generate(input, output, step, name string) error {
	data, err := os.ReadFile(input)
	if err != nil {
		return err
	}

	var task map[string]any
	if err := yaml.Unmarshal(data, &task); err != nil {
		return err
	}

	if err := convert(task, step, name); err != nil {
		return err
	}

	data, err = yaml.Marshal(task)
	if err != nil {
		return err
	}

	if err := os.MkdirAll(filepath.Dir(output), 0755); err != nil {
		return err
	}

	return os.WriteFile(output, append([]byte("# Generated by task-generator/remote; do not edit.\n"), data...), 0644)
}

// main reports generation errors with a failing process exit status.
func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
